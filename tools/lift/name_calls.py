#!/usr/bin/env python3
"""Name the routines the hand ports call and jump to.

    python tools/lift/name_calls.py [--dry]

Writes `crates/dune-rec/src/hand/entry.rs`: one constant per seg000 entry
that has a name, `pub const LINK_TROOP: u16 = 0x851f;`, the name being
the hand port's (upper-cased) or, for a routine without a port, the
listing's label when it is more than an address (`loc_`/`sub_` labels
are left out). Then rewrites, in every hand module, `c.call(0xADDR, ` and
`c.jump(0xADDR)` (and `c.call_far`-free forms only), and a routine handed
as an argument (`troops::run_for_each_troop(&mut c, 0xADDR, ..)`,
`tasks::add_task`, `screen::transition_drawn`, ...), whose ADDR has such a
constant to `c.call(entry::NAME, ` / `c.jump(entry::NAME)` / `entry::NAME`, adding
`use super::entry;` where needed. The constants are the same numbers, so
the ports do exactly what they did; the build is the check.

An entry whose port serves several entries (one fn, `match start`) gets
the fn's name only for its first entry in the table; the others get the
listing's label if it names them, else stay numbers. Run it again after
adding or renaming ports: it regenerates `entry.rs` and names the new
call sites.
"""
import os
import re
import sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
HAND = os.path.join(REPO, 'crates', 'dune-rec', 'src', 'hand')
LST = os.path.join(REPO, '..', 'Cryogenic', 'doc', 'DNCDPRG.lst')


def main():
    dry = '--dry' in sys.argv
    mod = open(os.path.join(HAND, 'mod.rs'), 'rb').read().decode('utf-8')  # keeps its CRLF
    table = re.findall(r'\(0x([0-9a-f]+), (\w+)::(\w+), "(\w+)"\)', mod)
    labels = {}
    if os.path.exists(LST):
        for line in open(LST, encoding='latin-1'):
            m = re.match(r'seg000:([0-9a-f]{4})\s+(\w+):\s', line)
            if m:
                labels.setdefault(int(m.group(1), 16), m.group(2))
    names = {}  # address -> const name
    used = {}   # const name -> address
    first_of_fn = set()

    def take(a, n):
        n = n.upper()
        if not re.match(r'[A-Z_][A-Z0-9_]*$', n) or a in names:
            return
        if n in used and used[n] != a:
            return
        names[a] = n
        used[n] = a

    def descriptive(label):
        return label and not re.match(r'(loc|sub|nullsub|unk|locret|byte|word)_', label)

    for a, modname, fn, label in table:
        a = int(a, 16)
        if (modname, fn) not in first_of_fn:
            first_of_fn.add((modname, fn))
            take(a, fn)
        elif descriptive(label):
            take(a, label)
    for a, label in labels.items():
        if descriptive(label):
            take(a, label)

    out = ['//! The seg000 routines the hand ports call or jump to, by name.',
           '//!',
           '//! Generated by `tools/lift/name_calls.py` (the hand port\'s name, else',
           '//! the listing\'s label); `c.call(entry::LINK_TROOP, ret)`.',
           '#![allow(dead_code)]',
           '']
    rx_call = re.compile(r'\bc\.call\(0x([0-9a-f]+), ')
    rx_jump = re.compile(r'\bc\.jump\(0x([0-9a-f]+)\)')
    # A routine handed to another as an argument (the named calls that set
    # it in BP or SI: the troop loops, the frame tasks, the transitions).
    rx_arg = re.compile(r'\b((?:\w+::)?(?:run_for_\w+|add_task|remove_task|transition_drawn|draw_on_front_buffer'
                        r'|draw_then_wait|set_click))\(((?:&mut )?c, )0x([0-9a-f]+)\b')
    wanted = set()
    files = sorted(f for f in os.listdir(HAND) if f.endswith('.rs') and f not in ('entry.rs', 'mod.rs'))
    texts = {}
    for f in files:
        raw = open(os.path.join(HAND, f), 'rb').read().decode('utf-8')
        texts[f] = raw
        for rx in (rx_call, rx_jump):
            for h in rx.findall(raw):
                if int(h, 16) in names:
                    wanted.add(int(h, 16))
        for _, _, h in rx_arg.findall(raw):
            if int(h, 16) in names:
                wanted.add(int(h, 16))
        # The names already written (an earlier run) stay.
        for n in re.findall(r'\bentry::([A-Z0-9_]+)', raw):
            assert n in used, f'{f}: entry::{n} is no longer a name (renamed port?)'
            wanted.add(used[n])
    for a in sorted(wanted):
        out.append(f'pub const {names[a]}: u16 = 0x{a:04x};')
    entry_src = '\n'.join(out) + '\n'
    changed = 0
    sites = 0
    for f, raw in texts.items():
        def sub_call(m):
            a = int(m.group(1), 16)
            return f'c.call(entry::{names[a]}, ' if a in names else m.group(0)

        def sub_jump(m):
            a = int(m.group(1), 16)
            return f'c.jump(entry::{names[a]})' if a in names else m.group(0)
        t, n1 = rx_call.subn(sub_call, raw)
        t, n2 = rx_jump.subn(sub_jump, t)

        def sub_arg(m):
            a = int(m.group(3), 16)
            return f'{m.group(1)}({m.group(2)}entry::{names[a]}' if a in names else m.group(0)
        t, n3 = rx_arg.subn(sub_arg, t)
        if t == raw:
            continue
        sites += t.count('entry::') - raw.count('entry::')
        if not re.search(r'^use super::entry;', t, re.M):
            nl = '\r\n' if '\r\n' in t else '\n'
            m = re.search(r'^use super::', t, re.M) or re.search(r'^use ', t, re.M)
            t = t[:m.start()] + 'use super::entry;' + nl + t[m.start():]
        changed += 1
        if not dry:
            open(os.path.join(HAND, f), 'wb').write(t.encode('utf-8'))
    if not dry:
        open(os.path.join(HAND, 'entry.rs'), 'w', encoding='utf-8', newline='\n').write(entry_src)
        if not re.search(r'^(pub )?mod entry;', mod, re.M):
            nl = '\r\n' if '\r\n' in mod else '\n'
            m = re.search(r'^(pub )?mod \w+;', mod, re.M)
            mod = mod[:m.start()] + 'pub mod entry;' + nl + mod[m.start():]
            open(os.path.join(HAND, 'mod.rs'), 'wb').write(mod.encode('utf-8'))
    print(f'{len(wanted)} names, {sites} sites in {changed} files')


if __name__ == '__main__':
    main()
